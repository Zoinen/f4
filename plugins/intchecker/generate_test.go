func TestExistingOutputs(t *testing.T) {
	dir := t.TempDir()
	writeTestFile(t, dir, "a.txt", "abc")
	writeTestFile(t, dir, "b.txt", "abc")
	writeTestFile(t, dir, "b.txt.md5", "old")
	writeTestFile(t, dir, "list.md5", "old")
	fs := vfs.NewOSVFS(dir)
	job := generateJob{fs: fs, dir: dir, names: []string{"a.txt", "b.txt", "b.txt.md5", "gone"}, algorithm: AlgMD5, output: "list.md5"}
	for _, tc := range []struct {
		mode outputMode
		want []string
	}{
		{outputSingle, []string{"list.md5"}},
		{outputSeparate, []string{"b.txt.md5"}},
		{outputDirectory, nil},
		{outputDisplay, nil},
	} {
		job.mode = tc.mode
		var ignored generateResult
		inputs, err := collectInputs(context.Background(), job, &ignored, nil)
		if err != nil {
			t.Fatal(err)
		}
		got, err := existingOutputs(context.Background(), job, inputs)
		if err != nil {
			t.Fatal(err)
		}
		if len(got) != len(tc.want) || (len(got) > 0 && got[0] != tc.want[0]) {
			t.Errorf("mode %d: existing = %q, want %q", tc.mode, got, tc.want)
		}
	}
}
