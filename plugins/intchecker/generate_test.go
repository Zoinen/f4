type recordingReporter struct {
	calls     int
	lastTotal int
	lastSpeed string
	files     map[string]bool
}

func (r *recordingReporter) UpdateTransfer(action, filename string, currentPct int, totalText string, totalPct int, speedText string) {
	r.calls++
	r.lastTotal = totalPct
	r.lastSpeed = speedText
	if r.files == nil {
		r.files = map[string]bool{}
	}
	r.files[filename] = true
	if currentPct < 0 || currentPct > 100 || totalPct < 0 || totalPct > 100 {
		panic("progress out of range")
	}
}

func writeTestFile(t *testing.T, dir, name, content string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

func readTestFile(t *testing.T, dir, name string) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(dir, name))
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func TestRunGenerateWritesSortedSingleFile(t *testing.T) {
	dir := t.TempDir()
	writeTestFile(t, dir, "b.txt", "abc")
	writeTestFile(t, dir, "a.txt", "abc")
	if err := os.Mkdir(filepath.Join(dir, "sub"), 0o700); err != nil {
		t.Fatal(err)
	}
	reporter := &recordingReporter{}
	job := generateJob{fs: vfs.NewOSVFS(dir), dir: dir, names: []string{"b.txt", "sub", "a.txt", ".."}, algorithm: AlgSHA256, output: "out.sha256"}
	res, err := runGenerate(context.Background(), job, reporter)
	if err != nil {
		t.Fatal(err)
	}
	if res.Written != 2 || len(res.Skipped) != 1 || res.Skipped[0] != "sub" || len(res.Failures) != 0 {
		t.Fatalf("result = %+v", res)
	}
	want := abcDigests[AlgSHA256] + " *a.txt\n" + abcDigests[AlgSHA256] + " *b.txt\n"
	if got := readTestFile(t, dir, "out.sha256"); got != want {
		t.Fatalf("checksum file =\n%q\nwant\n%q", got, want)
	}
	if reporter.lastTotal != 100 || !reporter.files["a.txt"] || !reporter.files["b.txt"] {
		t.Fatalf("progress = %+v", reporter)
	}
	// Progress carries elapsed time, ETA and hashing speed (issue #1623,
	// author's 3rd request): every UpdateTransfer call gets a non-empty
	// speed/time text, not just the final one.
	if reporter.lastSpeed == "" {
		t.Fatalf("progress speed/time text is empty")
	}
}

