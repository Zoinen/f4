func TestRunGenerateCancelledWritesNothing(t *testing.T) {
	dir := t.TempDir()
	writeTestFile(t, dir, "a.txt", "abc")
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	job := generateJob{fs: vfs.NewOSVFS(dir), dir: dir, names: []string{"a.txt"}, algorithm: AlgMD5, output: "out.md5"}
	if _, err := runGenerate(ctx, job, &recordingReporter{}); !errors.Is(err, context.Canceled) {
		t.Fatalf("err = %v, want context.Canceled", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "out.md5")); !os.IsNotExist(err) {
		t.Fatalf("cancelled run left a checksum file: %v", err)
	}
}

