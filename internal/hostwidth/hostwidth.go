// Package hostwidth is the width table and lookup of the ConPTY host that f4
// bundles (Windows Terminal's OpenConsole, pinned to commit
// e9b4e2e18fb1b9cee6839969d42cd0f95d228926): a port of its
// CodepointWidthDetector (src/types/CodepointWidthDetector.cpp) and of
// GetQuickCharWidth (src/types/convert.cpp), Copyright (c) Microsoft Corporation,
// MIT license.
//
// It exists as a unit of compatibility, not as an opinion about widths
// (unxed/f4#1681, section 2 of the ConPTY notes). The bundled host keeps one
// wchar_t per cell and counts a glyph's columns with this table, so when f4
// interprets the host's own cursor commands within a line -- CR, CHA, CUP, EL --
// it has to count the same way, or it misses the cell the host aimed at. What
// the user sees is laid out by f4's own, correct measure (uniseg); this table
// must not be used for that.
package hostwidth

// Width is the class the host gives a codepoint.
type Width uint8

const (
	// Narrow is one column.
	Narrow Width = iota
	// Wide is two columns.
	Wide
	// Ambiguous could be narrow or wide depending on codepage and font; the host
	// asks the renderer where it can, and counts one column where it cannot.
	Ambiguous
)

func (w Width) String() string {
	switch w {
	case Narrow:
		return "narrow"
	case Wide:
		return "wide"
	}
	return "ambiguous"
}

type span struct {
	lo, hi rune
	w      Width
}

