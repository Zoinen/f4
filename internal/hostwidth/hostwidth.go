// Lookup is the host's GetWidth for one codepoint, with no font fallback:
// printable ASCII is narrow at once (GetQuickCharWidth), everything else is
// looked up in the table by binary search, and a codepoint that is not in it is
// narrow. A codepoint above U+10FFFF or a lone surrogate is not a glyph; the
// host would be handed UTF-16 units for those, so they report Wide, its
// "better too wide than too narrow" answer when it cannot tell.
func Lookup(cp rune) Width {
	if cp >= 0x20 && cp <= 0x7e {
		return Narrow
	}
	if cp < 0 || cp > 0x10ffff || (cp >= 0xd800 && cp <= 0xdfff) {
		return Wide
	}
	lo, hi := 0, len(spans)
	for lo < hi {
		mid := int(uint(lo+hi) >> 1)
		if spans[mid].hi < cp {
			lo = mid + 1
		} else {
			hi = mid
		}
	}
	if lo < len(spans) && cp >= spans[lo].lo && cp <= spans[lo].hi {
		return spans[lo].w
	}
	return Narrow
}

// Columns is how many columns the host counts for a codepoint: two for Wide,
// one otherwise (an Ambiguous glyph counts one where there is no font to ask).
func Columns(cp rune) int {
	if Lookup(cp) == Wide {
		return 2
	}
	return 1
}
